# Intent: verify valid PNG bytes are accepted and normalized.
# Ensures: detected metadata matches the image content.
def test_validate_pet_image_accepts_a_valid_png() -> None:
    image_bytes = make_image_bytes("PNG")

    validated_image = pet_photos.validate_pet_image(image_bytes)

