# Intent: verify photo creation uploads the object before persisting its record.
# Ensures: the generated key, database record, and transaction state are consistent.
def test_create_pet_photo_uploads_the_object_and_persists_the_record(
    fake_storage_client: FakeObjectStorageClient,
) -> None:
    pet_id = uuid4()
    shelter_id = uuid4()

    # Critical setup: the service first resolves the pet and next sort order.
    fake_database_session = FakeDatabaseSession(
        [
            SimpleNamespace(id=pet_id),
            0,
        ]
    )

    validated_image = pet_photos.validate_pet_image(make_image_bytes("PNG"))

    photo = create_pet_photo(
        cast(Session, fake_database_session),
        pet_id=pet_id,
        shelter_id=shelter_id,
        image=validated_image,
        alt_text="Orange dog sitting outside.",
    )

    # Critical assertion: storage uses a server-generated object key.
    assert len(fake_storage_client.put_calls) == 1
    assert fake_storage_client.put_calls[0]["Bucket"] == settings.minio_bucket
    assert fake_storage_client.put_calls[0]["ContentType"] == "image/png"
    assert fake_storage_client.put_calls[0]["Key"].startswith(f"pets/{pet_id}/photos/")

    # Critical assertion: persistence occurs only after a successful upload.
    assert fake_database_session.added_objects == [photo]
    assert fake_database_session.commit_calls == 1
    assert fake_database_session.rollback_calls == 0

    assert photo.pet_id == pet_id
    assert photo.alt_text == "Orange dog sitting outside."
    assert photo.sort_order == 0
    assert photo.object_key == fake_storage_client.put_calls[0]["Key"]


# Intent: verify storage failures prevent database writes.
# Ensures: the service raises a storage error and leaves no persisted record.
def test_create_pet_photo_returns_storage_error_when_minio_upload_fails(
    fake_storage_client: FakeObjectStorageClient,
) -> None:
    fake_storage_client.fail_upload = True

    pet_id = uuid4()
    fake_database_session = FakeDatabaseSession(
        [
            SimpleNamespace(id=pet_id),
            0,
        ]
    )

    validated_image = pet_photos.validate_pet_image(make_image_bytes("PNG"))

    with pytest.raises(PetPhotoStorageError, match="could not be uploaded"):
        create_pet_photo(
            cast(Session, fake_database_session),
            pet_id=pet_id,
            shelter_id=uuid4(),
            image=validated_image,
            alt_text="Orange dog sitting outside.",
        )

    # Critical assertion: failed uploads must not mutate the database.
    assert fake_database_session.added_objects == []
    assert fake_database_session.commit_calls == 0
    assert fake_storage_client.delete_calls == []


# Intent: verify database failures clean up an already-uploaded object.
# Ensures: the transaction rolls back and no orphaned storage object remains.
def test_create_pet_photo_deletes_the_object_when_database_commit_fails(
    fake_storage_client: FakeObjectStorageClient,
) -> None:
    pet_id = uuid4()

    fake_database_session = FakeDatabaseSession(
        [
            SimpleNamespace(id=pet_id),
            0,
        ],
        fail_commit=True,
    )

    validated_image = pet_photos.validate_pet_image(make_image_bytes("WEBP"))

    with pytest.raises(PetPhotoPersistenceError, match="could not be saved"):
        create_pet_photo(
            cast(Session, fake_database_session),
            pet_id=pet_id,
            shelter_id=uuid4(),
            image=validated_image,
            alt_text="Dog wearing a blue collar.",
        )

    # Critical assertion: the database transaction is rolled back.
    assert fake_database_session.rollback_calls == 1

    # Critical assertion: the uploaded object is removed after persistence fails.
    assert len(fake_storage_client.put_calls) == 1
    assert len(fake_storage_client.delete_calls) == 1

    uploaded_key = fake_storage_client.put_calls[0]["Key"]
    deleted_key = fake_storage_client.delete_calls[0]["Key"]

    assert deleted_key == uploaded_key
    assert fake_storage_client.delete_calls[0]["Bucket"] == settings.minio_bucket


# Intent: verify a shelter owner can upload a valid pet photo.
# Ensures: the photo is stored, persisted, and returned without exposing its object key.
def test_shelter_owner_can_upload_pet_photo(
    client: TestClient,
    database_session: Session,
    fake_storage_client: FakeObjectStorageClient,
) -> None:
    _, owner_token = register_and_login_for_photo(
        client,
        email="photo-owner@example.com",
        display_name="Photo Shelter Owner",
    )

    create_shelter_for_photo(client, owner_token)
    pet = create_pet_for_photo(client, owner_token)

    image_bytes = make_image_bytes("PNG")

    response = client.post(
        f"/api/v1/pets/{pet['id']}/photos",
        headers={"Authorization": f"Bearer {owner_token}"},
        # Uploaded files and normal form values must be sent separately.
        files={
            "image_file": (
                "luna.png",
                image_bytes,
                "image/png",
            )
        },
        data={
            "alt_text": "Luna sitting beside a red ball.",
        },
    )

    assert response.status_code == 201

    response_data = response.json()

    assert response_data["pet_id"] == pet["id"]
    assert response_data["alt_text"] == "Luna sitting beside a red ball."
    assert response_data["sort_order"] == 0

    # The internal MinIO key must not be exposed through the public schema.
    assert "object_key" not in response_data

    # The fake client proves that the route attempted exactly one upload.
    assert len(fake_storage_client.put_calls) == 1
    assert fake_storage_client.put_calls[0]["ContentType"] == "image/png"
    assert fake_storage_client.put_calls[0]["Key"].startswith(f"pets/{pet['id']}/photos/")

    stored_photo = database_session.scalar(
        select(PetPhoto).where(PetPhoto.id == UUID(response_data["id"]))
    )

    assert stored_photo is not None
    assert stored_photo.pet_id == UUID(pet["id"])
    assert stored_photo.object_key == fake_storage_client.put_calls[0]["Key"]


# Intent: verify ordinary shelter staff cannot upload pet photos.
# Ensures: authorization rejects the request before object storage is called.
def test_staff_member_cannot_upload_pet_photo(
    client: TestClient,
    database_session: Session,
    fake_storage_client: FakeObjectStorageClient,
) -> None:
    _, owner_token = register_and_login_for_photo(
        client,
        email="staff-test-owner@example.com",
        display_name="Staff Test Owner",
    )

    shelter = create_shelter_for_photo(client, owner_token)
    pet = create_pet_for_photo(client, owner_token)

    staff_user, staff_token = register_and_login_for_photo(
        client,
        email="photo-staff@example.com",
        display_name="Photo Staff",
    )

    database_session.add(
        ShelterMember(
            shelter_id=UUID(shelter["id"]),
            user_id=UUID(staff_user["id"]),
            role=ShelterMemberRole.STAFF,
        )
    )
    database_session.commit()

    response = client.post(
        f"/api/v1/pets/{pet['id']}/photos",
        headers={"Authorization": f"Bearer {staff_token}"},
        files={
            "image_file": (
                "luna.png",
                make_image_bytes("PNG"),
                "image/png",
            )
        },
        data={"alt_text": "Luna outside."},
    )

    assert response.status_code == 403
    assert response.json() == {"detail": "Shelter owner or manager access is required."}

    # Authorization happens before the file reaches object storage.
    assert fake_storage_client.put_calls == []


