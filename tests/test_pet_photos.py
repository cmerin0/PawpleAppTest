# Auxiliary database double used to isolate service tests from PostgreSQL. It
# supplies the scalar query results expected by the service and records add,
# commit, and rollback calls so tests can verify transaction behavior.
class FakeDatabaseSession:
    def __init__(
        self,
        scalar_results: list[object | None],
        *,
        fail_commit: bool = False,
    ) -> None:
        self._scalar_results = iter(scalar_results)
        self.added_objects: list[object] = []
        self.commit_calls = 0
        self.rollback_calls = 0
        self.fail_commit = fail_commit

    def scalar(self, statement: object) -> object | None:
        del statement
        return next(self._scalar_results)

    def add(self, instance: object) -> None:
        self.added_objects.append(instance)

    def commit(self) -> None:
        self.commit_calls += 1

        if self.fail_commit:
            raise SQLAlchemyError("Simulated database failure.")

    def refresh(self, instance: object) -> None:
        del instance

    def rollback(self) -> None:
        self.rollback_calls += 1


# Auxiliary object-storage double used to isolate tests from MinIO. It records
# upload and deletion arguments, and can raise a boto3-compatible error so the
# tests cover both successful uploads and failure cleanup paths.
class FakeObjectStorageClient:
    def __init__(self) -> None:
        self.put_calls: list[dict[str, Any]] = []
        self.delete_calls: list[dict[str, Any]] = []
        self.fail_upload = False

    def put_object(self, **kwargs: Any) -> dict[str, Any]:
        if self.fail_upload:
            raise ClientError(
                {"Error": {"Code": "InternalError", "Message": "Storage failed."}},
                "PutObject",
            )

        self.put_calls.append(kwargs)
        return {}

    def delete_object(self, **kwargs: Any) -> dict[str, Any]:
        self.delete_calls.append(kwargs)
        return {}


# Auxiliary fixture that replaces the production storage client with the fake
# client for the duration of each test and automatically restores the patch.
@pytest.fixture
def fake_storage_client(
    monkeypatch: pytest.MonkeyPatch,
) -> Iterator[FakeObjectStorageClient]:
    fake_client = FakeObjectStorageClient()

    monkeypatch.setattr(
        pet_photos,
        "get_object_storage_client",
        lambda: fake_client,
    )

    yield fake_client


# Auxiliary image factory that creates valid, tiny image files in memory. The
# generated bytes let tests exercise content-based format detection without
# reading fixtures from disk or making assumptions based on file extensions.
def make_image_bytes(image_format: str = "PNG") -> bytes:
    image_buffer = BytesIO()

    with Image.new("RGB", (20, 20), color="orange") as image:
        image.save(image_buffer, format=image_format)

    return image_buffer.getvalue()


# Auxiliary API setup helper that creates a unique test user and logs them in.
# It returns both the response data and bearer token needed by photo endpoints.
def register_and_login_for_photo(
    client: TestClient,
    *,
    email: str,
    display_name: str,
) -> tuple[dict[str, Any], str]:
    """Create a user and return their data and authentication token."""
    registration_response = client.post(
        "/api/v1/users",
        json={
            "email": email,
            "password": "test-password",
            "display_name": display_name,
        },
    )

    assert registration_response.status_code == 201

    login_response = client.post(
        "/api/v1/auth/login",
        json={
            "email": email,
            "password": "test-password",
        },
    )

    assert login_response.status_code == 200

    return (
        registration_response.json(),
        login_response.json()["access_token"],
    )


